last_name			VARCHAR(50)			NOT NULL,
email				VARCHAR(150)		NOT NULL,
phone				VARCHAR(50)			NOT NULL,
organization_name	VARCHAR(50)			NOT NULL,
orgnization_type	VARCHAR(50)			NOT NULL,
content				VARCHAR(2000)		NOT NULL,
